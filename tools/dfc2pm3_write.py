#!/usr/bin/env python3
"""Generate a Proxmark3 Iceman `hf mfdes` personalization script from a .dfc
credential: the command sequence that WRITES a genuine blank DESFire card so it
matches the .dfc (Format -> CreateApplication -> ChangeKey -> CreateFile ->
WriteData).

Why this instead of emulation: a genuine NXP DESFire chip natively negotiates
the higher bitrates (212/424 kbit/s) that the operational reader demands and
that no 106-kbit/s emulator (Flipper, Proxmark `hf mfdes sim`, Chameleon) can
produce. Writing the credential onto a real blank chip sidesteps the RF wall.

The Proxmark3 (Iceman) is the writer: its `hf mfdes` client already implements
every DESFire personalization command. This script only emits the right command
lines, derived faithfully from the .dfc. Run them in the pm3 client with a blank
card on the antenna.

Usage:
    python dfc2pm3_write.py <input.dfc> [output.cmd]

Verified against the local Proxmark3 source (client/src/cmdhfmfdes.c) and the
dfc-core codec (lib/core/src/dfc_text.c, dfc_emulator_access.c):
  - access_rights nibbles: Read=bits12, Write=bits8, ReadWrite=bits4, Change=bits0
    -> the two .dfc bytes concatenate directly into `--rawrights` (no swap).
  - ks2 crypto bits [7:6]: 00=DES/2TDEA, 01=3TDEA(3K3DES), 10=AES.

ASSUMPTIONS (flagged inline, adjust on first hardware run):
  - A blank NXP DESFire ships with PICC master key = single DES, 8x 0x00.
    If PICC auth fails, try the AES default (16x 0x00, -t aes).
  - crypto-00 app/key algo is inferred from key LENGTH (8=des, 16=2tdea, 24=3tdea).
  - All-zero keys are treated as factory-default -> no ChangeKey emitted.
  - Files are created app-master-authenticated unless a free-create right applies;
    data is written authenticating with the key that holds Write (else ReadWrite).
"""
import sys
import re

# --- blank-card factory defaults -------------------------------------------
PICC_DEFAULT_ALGO = "des"
PICC_DEFAULT_KEY = "0000000000000000"  # 8x00, single DES
ZERO = {"des": "0000000000000000",
        "2tdea": "00000000000000000000000000000000",
        "3tdea": "000000000000000000000000000000000000000000000000",
        "aes": "00000000000000000000000000000000"}

COMM_AMODE = {0x00: "plain", 0x01: "mac", 0x02: "mac", 0x03: "encrypt"}
DSTALGO = {"des": "DES", "2tdea": "2TDEA", "3tdea": "3TDEA", "aes": "AES"}


def parse_dfc(text):
    d = {}
    for line in text.splitlines():
        s = line.strip()
        if not s or ":" not in s:
            continue
        k, v = s.split(":", 1)
        d[k.strip()] = v.strip()
    return d


def hx(v):
    return re.sub(r"[^0-9A-Fa-f]", "", v or "").upper()


def is_zero(key_hex):
    return len(key_hex) > 0 and set(key_hex) <= {"0"}


def algo_from_ks2(ks2, key_hex):
    crypto = (ks2 >> 6) & 0x03
    if crypto == 0x02:
        return "aes"
    if crypto == 0x01:
        return "3tdea"
    # crypto 00: DES or 2K3DES -- disambiguate by key length
    n = len(key_hex) // 2
    if n == 24:
        return "3tdea"
    if n == 16:
        return "2tdea"
    return "des"


def access_nibbles(ar_hex):
    ar = int(ar_hex, 16) if ar_hex else 0
    read = (ar >> 12) & 0xF
    write = (ar >> 8) & 0xF
    rw = (ar >> 4) & 0xF
    change = ar & 0xF
    return read, write, rw, change


def write_auth_key(write, rw):
    # pick the key number that can write: Write right, else ReadWrite right.
    for nib in (write, rw):
        if nib == 0xE:          # free
            return ("--no-auth", None)
        if nib <= 0x0D:         # a specific key
            return (None, nib)
    return ("DENY", None)       # both denied


def emit(d):
    out = []
    w = out.append

    gen = d.get("Card Generation", "EV3")
    storage = d.get("Card Storage", "?")
    uid = hx(d.get("UID", ""))
    w(f"# ---- DESFire personalization from .dfc ({gen}, {storage} bytes, UID {uid}) ----")
    w("# Generated by dfc2pm3_write.py. Put a BLANK DESFire card on the pm3 antenna.")
    w("# Run inside the pm3 client. Stop at the first error and report it.")
    w("")
    w("# --- 1. wipe to factory state (authenticates PICC master with defaults) ---")
    w("hf mfdes formatpicc")
    w(f"#   if this fails, auth first: hf mfdes auth -n 0 -t {PICC_DEFAULT_ALGO} -k {PICC_DEFAULT_KEY}")
    w(f"#   (blank EV3 may instead want AES default: hf mfdes auth -n 0 -t aes -k {ZERO['aes']})")
    w("")

    appcount = int(d.get("Application Count", "0"))

    # --- 2. create every application (PICC master auth = blank default) ---
    w("# --- 2. create applications ---")
    apps = []
    for ai in range(appcount):
        p = f"Application {ai:02X} "
        aid = hx(d.get(p + "AID", ""))
        if not aid:
            continue
        ks1 = hx(d.get(p + "Key Settings 1", "0F")) or "0F"
        ks2h = hx(d.get(p + "Key Settings 2", "00")) or "00"
        ks2 = int(ks2h, 16)
        numkeys = int(d.get(p + "Key Count", "1"))
        first_key = hx(d.get(p + "Key 00", ""))
        algo = algo_from_ks2(ks2, first_key)
        apps.append((ai, p, aid, ks2, numkeys, algo))

        line = (f"hf mfdes createapp -n 0 -t {PICC_DEFAULT_ALGO} -k {PICC_DEFAULT_KEY} "
                f"--aid {aid} --ks1 {ks1} --ks2 {ks2h} --dstalgo {DSTALGO[algo]} --numkeys {numkeys}")
        dfname = hx(d.get(p + "DF Name", ""))
        if dfname:
            # ISO DF name present; some cards also require an ISO FID here.
            line += f" --dfhex {dfname}"
        w(f"#   app {ai:02X}: AID {aid}, {algo}, {numkeys} key(s)")
        w(line)
    w("")

    # --- 3. change application keys away from default (skip zero = default) ---
    w("# --- 3. change application keys (only non-default keys) ---")
    any_key = False
    for (ai, p, aid, ks2, numkeys, algo) in apps:
        for ki in range(numkeys):
            kh = hx(d.get(p + f"Key {ki:02X}", ""))
            if not kh or is_zero(kh):
                continue
            any_key = True
            ver = hx(d.get(p + f"Key {ki:02X} Version", "00")) or "00"
            # auth with key0 (default, still zero at this point) of this app,
            # then set key ki. ChangeKey rights come from ks1[4:7] on the card.
            w(f"hf mfdes changekey --aid {aid} -t {algo} -n 0 -k {ZERO[algo]} "
              f"--newkeyno {ki:02X} --newkey {kh} --newver {ver}")
        # NOTE: if key 0 itself changes, change it LAST of this app (auth needs old key0).
    if not any_key:
        w("#   (all application keys are factory-default -> nothing to change)")
    w("")

    # --- 4. create files and write data ---
    w("# --- 4. create files + write data ---")
    for (ai, p, aid, ks2, numkeys, algo) in apps:
        fcount = int(d.get(p + "File Count", "0"))
        for fi in range(fcount):
            fp = f"{p}File {fi:02X} "
            num = hx(d.get(fp + "Number", ""))
            if not num:
                continue
            ftype = d.get(fp + "Type", "Standard Data")
            comm = int(hx(d.get(fp + "Communication Settings", "00")) or "0", 16)
            amode = COMM_AMODE.get(comm, "plain")
            ar = hx(d.get(fp + "Access Rights", "0000")) or "0000"
            size = int(d.get(fp + "Size", "0"))
            read, write, rw, change = access_nibbles(ar)

            backup = " --backup" if ftype == "Backup Data" else ""
            if ftype not in ("Standard Data", "Backup Data"):
                w(f"#   SKIP file {num} type '{ftype}' (value/record not handled here)")
                continue

            # create the file, authenticated as app master key 0 (default zero)
            w(f"#   app {aid} file {num}: {ftype}, comm {amode}, rights {ar}, size {size}")
            w(f"hf mfdes createfile --aid {aid} -n 0 -t {algo} -k {ZERO[algo]} "
              f"--fid {num} --amode {amode} --rawrights {ar} --size {size:06X}{backup}")

            # write the file data (only if non-zero), with a key that can write
            data = hx(d.get(fp + "Data", ""))
            if data and not is_zero(data):
                flag, keyno = write_auth_key(write, rw)
                if flag == "DENY":
                    w(f"#   WARNING: write denied by access rights {ar}; data not written")
                elif flag == "--no-auth":
                    w(f"hf mfdes write --aid {aid} --no-auth --fid {num} --type data -d {data}")
                else:
                    w(f"hf mfdes write --aid {aid} -n {keyno} -t {algo} -k {ZERO[algo]} "
                      f"--fid {num} --type data -d {data}")
            else:
                w(f"#   (file data all-zero -> freshly created file is already zero, write skipped)")
            if backup:
                w(f"hf mfdes write --aid {aid} --fid {num} --type data -d 00 --commit  # commit backup file")
        if fcount:
            w("")

    # --- 5. PICC master key / settings (LAST, if not factory-default) ---
    picc_key = hx(d.get("PICC Key 00", ""))
    picc_ks1 = hx(d.get("PICC Key Settings 1", "0F"))
    if picc_key and not is_zero(picc_key):
        w("# --- 5. change PICC master key LAST (after all apps exist) ---")
        picc_ks2 = int(hx(d.get("PICC Key Settings 2", "00")) or "0", 16)
        picc_algo = algo_from_ks2(picc_ks2, picc_key)
        ver = hx(d.get("PICC Key 00 Version", "00")) or "00"
        w(f"hf mfdes changekey -n 0 -t {PICC_DEFAULT_ALGO} -k {PICC_DEFAULT_KEY} "
          f"--newalgo {picc_algo} --newkey {picc_key} --newver {ver}")
        w(f"#   PICC key settings target ks1={picc_ks1}; set via a ChangeKeySettings if it differs from default 0x0F")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) < 2:
        sys.stderr.write(__doc__)
        return 2
    inp = argv[1]
    out = argv[2] if len(argv) > 2 else inp.rsplit(".", 1)[0] + ".pm3-write.cmd"
    with open(inp, "r", encoding="utf-8") as f:
        d = parse_dfc(f.read())
    script = emit(d)
    with open(out, "w", encoding="utf-8") as f:
        f.write(script)
    sys.stderr.write(f"Wrote {out}\n")
    sys.stdout.write(script)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
